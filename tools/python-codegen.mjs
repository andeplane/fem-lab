// Engine-owned schema → named Python methods and dataclass command envelopes.
// A parameter omitted in Python stays omitted on the wire, preserving engine defaults.
export function pythonBindings(doc) {
  const reserved = new Set('False None True and as assert async await break class continue def del elif else except finally for from global if import in is lambda nonlocal not or pass raise return try while with yield'.split(' '));
  const raw = name => name.replace(/([a-z0-9])([A-Z])/g, '$1_$2').replaceAll('.', '_').toLowerCase();
  const snake = name => reserved.has(raw(name)) ? raw(name) + '_' : raw(name);
  const param = key => /^[A-Z]/.test(key) ? key : snake(key);
  const type = prop => prop.type === 'string' ? 'str' : prop.type === 'boolean' ? 'bool' : prop.type === 'integer' ? 'int' : prop.type === 'number' ? 'float' : 'Any';
  const variants = ['commands', 'queries'].flatMap(root => doc[root].oneOf.map(v => ({v, tag:root === 'commands' ? 'cmd' : 'query'})));
  const lines = ['# Generated by tools/codegen.mjs; do not edit.', 'from __future__ import annotations', 'from dataclasses import dataclass', 'from typing import Any', 'from .client import OMIT, Command', ''];
  for (const {v,tag} of variants) {
    const wire=v.properties[tag].const;
    const cls=snake(wire).split('_').map(s=>s[0].toUpperCase()+s.slice(1)).join('')+'Args';
    const fields=Object.entries(v.properties).filter(([key])=>key!==tag);
    lines.push('@dataclass(kw_only=True)', `class ${cls}(Command):`, `    ${JSON.stringify(v.description??wire)}`, `    _tag = ${JSON.stringify(tag)}`, `    _name = ${JSON.stringify(wire)}`);
    for (const [key,prop] of fields) lines.push(`    ${param(key)}: ${type(prop)}${(v.required??[]).includes(key)?'':' = OMIT'}`);
    lines.push(`    _keys = ${JSON.stringify(Object.fromEntries(fields.map(([key])=>[param(key),key])))}`, '');
  }
  for (const async of [false,true]) {
    lines.push(`class ${async?'AsyncAPI':'API'}:`, '    _call: Any');
    for (const {v,tag} of variants) {
      const wire=v.properties[tag].const; const name=snake(wire);
      const fields=Object.entries(v.properties).filter(([key])=>key!==tag);
      const args=fields.map(([key,prop])=>`${param(key)}: ${type(prop)}${(v.required??[]).includes(key)?'':' = OMIT'}`);
      const cls=name.split('_').map(s=>s[0].toUpperCase()+s.slice(1)).join('')+'Args';
      lines.push(`    ${async?'async ':''}def ${name}(self${args.length?', *, '+args.join(', '):''}) -> Any:`, `        ${JSON.stringify(v.description??wire)}`, `        return ${async?'await ':''}self._call(${JSON.stringify(tag==='cmd'?'dispatch':'query')}, ${cls}(${fields.map(([key])=>`${param(key)}=${param(key)}`).join(', ')}).wire())`, '');
    }
  }
  return lines.join('\n').trimEnd()+'\n';
}
