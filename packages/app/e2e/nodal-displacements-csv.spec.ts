/** Read the actual downloaded CSV, including quoted source names and escaped quotes. */
function csv(text: string): string[][] {
  const rows: string[][] = [];
  let cells: string[] = [], cell = '', quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i]!;
    if (c === '"') {
      if (quoted && text[i + 1] === '"') { cell += '"'; i++; }
      else quoted = !quoted;
    } else if (c === ',' && !quoted) { cells.push(cell); cell = ''; }
    else if (c === '\n' && !quoted) { rows.push([...cells, cell.replace(/\r$/, '')]); cells = []; cell = ''; }
    else cell += c;
  }
  if (cell || cells.length) rows.push([...cells, cell.replace(/\r$/, '')]);
  expect(quoted, 'download has balanced CSV quotes').toBe(false);
  return rows;
}

test('@cpu nodal CSV download preserves repeated local Abaqus labels, instance identities and SI displacements', async ({ page }, info) => {
  await page.addInitScript(() => { localStorage.setItem('femlab.tour.dismissed', '1'); localStorage.setItem('femlab.autosave', 'off'); });
  await page.goto('./');
  await page.waitForFunction(() => Boolean(window.fem));
  const bar = await readFile(new URL('../../../crates/engine/tests/fixtures/abaqus-static/bar-hex-mm-n.inp', import.meta.url), 'utf8');
  // Two independently supported axial bars, with identical sparse local labels. This is
  // deliberately authored from the analytical bar fixture, not generated by an exporter.
  const mesh = bar.slice(bar.indexOf('*NODE'), bar.indexOf('*MATERIAL')).replace('*ELEMENT,', '9001,125,75,25\n*ELEMENT,');
  const text = `*PART,NAME="Bar, part"\n${mesh}*SOLID SECTION,ELSET=SOLID,MATERIAL=STEEL\n*END PART\n*ASSEMBLY,NAME=ASSEMBLY\n*INSTANCE,NAME="first, instance",PART="Bar, part"\n*END INSTANCE\n*INSTANCE,NAME=second,PART="Bar, part"\n0,200,0\n*END INSTANCE\n*NSET,NSET=ROOTS,INSTANCE="first, instance"\n101,114,127,140\n*NSET,NSET=ROOTS,INSTANCE=second\n101,114,127,140\n*NSET,NSET=TIPS,INSTANCE="first, instance"\n205,218,231,244\n*NSET,NSET=TIPS,INSTANCE=second\n205,218,231,244\n*END ASSEMBLY\n*MATERIAL,NAME=STEEL\n*ELASTIC\n200000,0\n*BOUNDARY\nROOTS,1,3\n*STEP,NAME=AXIAL\n*STATIC\n*CLOAD\nTIPS,1,250\n*END STEP\n`;
  await page.evaluate(text => window.fem.dispatch({ cmd: 'file.importAbaqus', text, name: 'source comparison', body: 'bars', mode: 'static', unitLength: '1 mm', unitForce: '1 N' }), text);
  await page.getByRole('dialog', { name: 'Abaqus import report', exact: true }).getByTitle('Close Abaqus import report', { exact: true }).click();
  await page.evaluate(() => window.fem.dispatch({ cmd: 'solve.run', step: 'AXIAL', solver: 'cpu-direct' }));
  const before = await page.evaluate(async () => ({
    document: await window.fem.query.document(), journal: await window.fem.query.journal(),
    result: await window.fem.registry.query({ query: 'query.result', step: 'AXIAL' }) as ResultSummary,
    field: await window.fem.registry.query({ query: 'query.field', step: 'AXIAL', field: 'displacement' }) as { values: number[] },
    camera: await window.fem.registry.query({ query: 'query.view' }),
  }));
  await page.evaluate(() => window.fem.dispatch({ cmd: 'panel.toggle', panel: 'export', open: true }));
  const dialog = page.getByRole('dialog', { name: 'Export', exact: true });
  const row = dialog.locator('.export-row').filter({ has: page.getByText('Nodal displacements (CSV)', { exact: true }) });
  await expect(row).toBeVisible();
  await expect(row).toContainText('"step":"AXIAL"');
  const downloading = page.waitForEvent('download');
  await row.getByRole('button', { name: 'export', exact: true }).click();
  const download = await downloading;
  expect(download.suggestedFilename()).toBe('source comparison-nodal-displacements.csv');
  const saved = info.outputPath('source-comparison-nodal-displacements.csv');
  await download.saveAs(saved);
  const bytes = await readFile(saved, 'utf8');
  expect(bytes).toContain('"first, instance"');
  expect(bytes).toContain('"Bar, part"');
  const [header, ...records] = csv(bytes);
  expect(header).toEqual(['resultId', 'step', 'nodeIndex', 'normalizedLabel', 'sourceLabel', 'instance', 'part', 'x_m', 'y_m', 'z_m', 'ux_m', 'uy_m', 'uz_m', 'status']);
  expect(records).toHaveLength(26);
  const computed = records.filter(record => record[13] === 'computed');
  expect(computed).toHaveLength(24);
  const identities = new Set<string>(), normalized = new Set<string>();
  const sourceLabels = [101, 114, 127, 140, 153, 166, 179, 192, 205, 218, 231, 244];
  for (const record of computed) {
    const [resultId, step, nodeIndex, label, sourceLabel, instance, part, x, y, z, ux, uy, uz] = record;
    expect(resultId).toBe(before.result.resultId); expect(step).toBe('AXIAL');
    expect(part).toBe('Bar, part');
    expect(['first, instance', 'SECOND']).toContain(instance);
    expect(sourceLabels).toContain(Number(sourceLabel));
    identities.add(`${instance}/${sourceLabel}`); normalized.add(label!);
    const local = sourceLabels.indexOf(Number(sourceLabel));
    const expectedX = Math.floor(local / 4) * 0.5;
    expect(Number(x)).toBe(expectedX);
    expect(Number(y)).toBeCloseTo((instance === 'SECOND' ? 0.2 : 0) + (local % 2 ? 0.1 : 0), 14);
    expect(Number(z)).toBe(local % 4 >= 2 ? 0.1 : 0);
    // u = F x / E A; E=200 GPa, A=.01 m² and F=1000 N for EACH bar.
    expect(Math.abs(Number(ux) - 5e-7 * expectedX)).toBeLessThan(1e-16);
    expect(Math.abs(Number(uy))).toBeLessThan(1e-16); expect(Math.abs(Number(uz))).toBeLessThan(1e-16);
    expect([Number(ux), Number(uy), Number(uz)]).toEqual(before.field.values.slice(Number(nodeIndex) * 3, Number(nodeIndex) * 3 + 3));
  }
  expect(identities.size).toBe(24); expect(normalized.size).toBe(24);
  const unused = records.filter(record => record[13] === 'unused');
  expect(unused).toHaveLength(2);
  for (const record of unused) {
    expect(record[2]).toBe(''); expect(record[4]).toBe('9001');
    expect(record.slice(10, 13)).toEqual(['', '', '']);
    expect(Number(record[7])).toBe(0.125); expect(Number(record[9])).toBe(0.025);
    expect(Number(record[8])).toBeCloseTo(record[5] === 'SECOND' ? 0.275 : 0.075, 14);
  }
  expect(await page.evaluate(async () => ({ document: await window.fem.query.document(), journal: await window.fem.query.journal(), result: await window.fem.registry.query({ query: 'query.result', step: 'AXIAL' }), camera: await window.fem.registry.query({ query: 'query.view' }) })))
    .toEqual({ document: before.document, journal: before.journal, result: before.result, camera: before.camera });
});

test('@cpu original published Abaqus assembly downloads all source-labelled nodal values for comparison', async ({ page }, info) => {
  test.setTimeout(120_000);
  await page.addInitScript(() => { localStorage.setItem('femlab.tour.dismissed', '1'); localStorage.setItem('femlab.autosave', 'off'); });
  await page.goto('./');
  await page.waitForFunction(() => Boolean(window.fem));
  const directory = new URL('../../../crates/engine/tests/fixtures/third-party/brief-finite-element-net/case06/', import.meta.url);
  const source = await readFile(new URL('Job-11.inp', directory));
  const reference = JSON.parse(await readFile(new URL('author-abaqus-probes-checked.json', directory), 'utf8')) as {
    source_deck_sha256: string; instance: string; node_count: number;
    displacements: Record<string, [number, number, number]>; coordinates: Record<string, [number, number, number]>;
  };
  expect(createHash('sha256').update(source).digest('hex')).toBe(reference.source_deck_sha256);
  // Published author results; Abaqus version is unknown and this test does not execute Abaqus.
  await page.evaluate(text => window.fem.dispatch({ cmd: 'file.importAbaqus', text, name: 'Published Abaqus comparison', body: 'beam', mode: 'static', unitLength: '1 m', unitForce: '1 N' }), source.toString('utf8'));
  await page.getByRole('dialog', { name: 'Abaqus import report', exact: true }).getByTitle('Close Abaqus import report', { exact: true }).click();
  const model = await page.evaluate(() => window.fem.registry.query({ query: 'query.model' })) as ModelSummary;
  const step = model.steps[0]!.name;
  await page.evaluate(step => window.fem.dispatch({ cmd: 'solve.run', step, solver: 'cpu-direct' }), step);
  const result = await page.evaluate(step => window.fem.registry.query({ query: 'query.result', step }), step) as ResultSummary;
  await page.evaluate(() => window.fem.dispatch({ cmd: 'panel.toggle', panel: 'export', open: true }));
  const row = page.getByRole('dialog', { name: 'Export', exact: true }).locator('.export-row').filter({ has: page.getByText('Nodal displacements (CSV)', { exact: true }) });
  const downloading = page.waitForEvent('download');
  await row.getByRole('button', { name: 'export', exact: true }).click();
  const download = await downloading;
  expect(download.suggestedFilename()).toBe('Published Abaqus comparison-nodal-displacements.csv');
  const saved = info.outputPath('published-abaqus-nodal-displacements.csv');
  await download.saveAs(saved);
  const [header, ...records] = csv(await readFile(saved, 'utf8'));
  expect(header).toEqual(['resultId', 'step', 'nodeIndex', 'normalizedLabel', 'sourceLabel', 'instance', 'part', 'x_m', 'y_m', 'z_m', 'ux_m', 'uy_m', 'uz_m', 'status']);
  expect(records).toHaveLength(reference.node_count);
  const maximum = Math.max(...Object.values(reference.displacements).flat().map(Math.abs));
  // Exactly the existing case06 corpus gate, including the author's printed precision.
  const tolerance = 1e-13 + 2e-6 * maximum;
  const checked = new Set<string>();
  for (const record of records) {
    expect(record[0]).toBe(result.resultId); expect(record[1]).toBe(step);
    expect(record[5]).toBe(reference.instance); expect(record[6]).toBe('BEAM'); expect(record[13]).toBe('computed');
    const label = record[4]!;
    expect(checked.has(label)).toBe(false); checked.add(label);
    expect(reference.displacements[label]).toBeDefined();
    record.slice(7, 10).forEach((value, component) => expect(Number(value)).toBeCloseTo(reference.coordinates[label]![component]!, 10));
    record.slice(10, 13).forEach((value, component) => expect(Math.abs(Number(value) - reference.displacements[label]![component]!)).toBeLessThanOrEqual(tolerance));
  }
  expect(checked.size).toBe(275);
});
